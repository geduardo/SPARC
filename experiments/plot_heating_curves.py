#!/usr/bin/env python3
"""
Plot heating curves from CSV files generated by track_segment_temperatures.py

This script reads CSV files containing segment temperature histories and creates
visualizations of the heating curves.

Usage:
    python plot_heating_curves.py                    # Plot all CSV files in heating_curves/
    python plot_heating_curves.py --dir custom_dir/  # Plot CSV files from custom directory
    python plot_heating_curves.py --files file1.csv file2.csv  # Plot specific files
"""

import argparse
import csv
import os
import glob
import numpy as np
import matplotlib.pyplot as plt
from datetime import datetime


def read_heating_curve_csv(filepath):
    """
    Read a heating curve CSV file and extract data.
    
    Returns:
        dict: Dictionary containing metadata and data arrays
    """
    metadata = {}
    data = {
        'time_ms': [],
        'temp_celsius': [],
        'time_us': [],
        'temp_kelvin': []
    }
    
    with open(filepath, 'r') as f:
        reader = csv.reader(f)
        
        # Read metadata from comment lines
        for row in reader:
            if not row or len(row) == 0:
                continue
                
            # Check if this is a metadata line
            if row[0].startswith('#'):
                line = row[0]
                if 'Segment Number:' in line:
                    metadata['segment_number'] = int(line.split(':')[1].strip())
                elif 'Inlet Time' in line:
                    metadata['inlet_time_us'] = float(line.split(':')[1].strip())
                elif 'Outlet Time' in line:
                    try:
                        metadata['outlet_time_us'] = float(line.split(':')[1].strip())
                    except ValueError:
                        metadata['outlet_time_us'] = None
                elif 'Transit Time' in line:
                    metadata['transit_time_ms'] = float(line.split(':')[1].strip().replace('ms', '').strip())
            # Check if this is the header row
            elif row[0] == 'Time_Since_Inlet_ms':
                # Next rows will be data
                break
        
        # Read data rows
        for row in reader:
            if not row or len(row) < 4:
                continue
            try:
                data['time_ms'].append(float(row[0]))
                data['temp_celsius'].append(float(row[1]))
                data['time_us'].append(float(row[2]))
                data['temp_kelvin'].append(float(row[3]))
            except ValueError:
                # Skip rows that can't be parsed
                continue
    
    # Convert lists to numpy arrays
    for key in data:
        data[key] = np.array(data[key])
    
    return {
        'metadata': metadata,
        'data': data,
        'filename': os.path.basename(filepath)
    }


def plot_single_curves(heating_curves, output_file=None):
    """
    Plot each heating curve in its own subplot.
    
    Args:
        heating_curves: List of heating curve dictionaries
        output_file: Optional filename to save the plot
    """
    n_curves = len(heating_curves)
    
    if n_curves == 0:
        print("No heating curves to plot!")
        return
    
    # Create figure with subplots
    fig, axes = plt.subplots(n_curves, 1, figsize=(12, 3 * n_curves))
    
    # Handle single subplot case
    if n_curves == 1:
        axes = [axes]
    
    for idx, curve in enumerate(heating_curves):
        ax = axes[idx]
        data = curve['data']
        metadata = curve['metadata']
        
        # Plot temperature vs time
        ax.plot(data['time_ms'], data['temp_celsius'], linewidth=1.5, color='steelblue')
        ax.set_xlabel('Time since inlet entry (ms)', fontsize=10)
        ax.set_ylabel('Temperature (°C)', fontsize=10)
        ax.set_title(f'Segment #{metadata.get("segment_number", idx+1)} Temperature Evolution',
                     fontsize=11, fontweight='bold')
        ax.grid(True, alpha=0.3)
        
        # Add statistics
        max_temp = np.max(data['temp_celsius'])
        min_temp = np.min(data['temp_celsius'])
        avg_temp = np.mean(data['temp_celsius'])
        transit_time = metadata.get('transit_time_ms', data['time_ms'][-1])
        
        textstr = (f"Transit time: {transit_time:.1f} ms\n"
                  f"Max temp: {max_temp:.1f}°C\n"
                  f"Min temp: {min_temp:.1f}°C\n"
                  f"Avg temp: {avg_temp:.1f}°C")
        
        ax.text(0.02, 0.98, textstr,
                transform=ax.transAxes,
                fontsize=9,
                verticalalignment='top',
                bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.5))
    
    plt.tight_layout()
    
    # Save or show
    if output_file:
        plt.savefig(output_file, dpi=150, bbox_inches='tight')
        print(f"✓ Figure saved: {output_file}")
    else:
        plt.show()


def plot_overlay_curves(heating_curves, output_file=None):
    """
    Plot all heating curves on the same axes for comparison.
    
    Args:
        heating_curves: List of heating curve dictionaries
        output_file: Optional filename to save the plot
    """
    if len(heating_curves) == 0:
        print("No heating curves to plot!")
        return
    
    fig, ax = plt.subplots(figsize=(12, 8))
    
    # Use a colormap for different segments
    colors = plt.cm.viridis(np.linspace(0, 1, len(heating_curves)))
    
    for idx, (curve, color) in enumerate(zip(heating_curves, colors)):
        data = curve['data']
        metadata = curve['metadata']
        segment_num = metadata.get('segment_number', idx+1)
        
        ax.plot(data['time_ms'], data['temp_celsius'], 
                linewidth=1.5, 
                color=color,
                label=f'Segment #{segment_num}',
                alpha=0.8)
    
    ax.set_xlabel('Time since inlet entry (ms)', fontsize=12)
    ax.set_ylabel('Temperature (°C)', fontsize=12)
    ax.set_title('Overlay of All Segment Temperature Histories', fontsize=14, fontweight='bold')
    ax.grid(True, alpha=0.3)
    ax.legend(loc='best', fontsize=9, ncol=2)
    
    plt.tight_layout()
    
    # Save or show
    if output_file:
        plt.savefig(output_file, dpi=150, bbox_inches='tight')
        print(f"✓ Figure saved: {output_file}")
    else:
        plt.show()


def resample_curve_with_averaging(time_ms, temp_celsius, resolution_ms=2.0):
    """
    Resample a heating curve to a fixed time resolution using proper low-pass filtering.
    
    This avoids aliasing by first applying a moving average filter (low-pass filter)
    and then interpolating at the desired resolution. This approach prevents sharp
    peaks and provides smooth downsampling.
    
    Args:
        time_ms: Array of time values in milliseconds
        temp_celsius: Array of temperature values in Celsius
        resolution_ms: Target time resolution in milliseconds (default: 2.0)
    
    Returns:
        tuple: (resampled_time_ms, resampled_temp_celsius)
    """
    if len(time_ms) == 0:
        return np.array([]), np.array([])
    
    # Step 1: Apply moving average filter to remove high frequencies
    # Window size should be proportional to the decimation factor
    # Calculate average spacing in original data
    avg_spacing = np.mean(np.diff(time_ms))
    
    # Window size: number of points that span approximately resolution_ms
    window_size = max(int(resolution_ms / avg_spacing), 1)
    
    # Make window size odd for symmetric filter
    if window_size % 2 == 0:
        window_size += 1
    
    # Apply moving average using convolution (more efficient than rolling window)
    if window_size > 1:
        # Create normalized window
        window = np.ones(window_size) / window_size
        # Apply filter with 'valid' mode to avoid edge effects initially
        # Then use 'same' to keep the same length
        filtered_temp = np.convolve(temp_celsius, window, mode='same')
        
        # Handle edges: use original values at boundaries where convolution is incomplete
        half_window = window_size // 2
        filtered_temp[:half_window] = temp_celsius[:half_window]
        filtered_temp[-half_window:] = temp_celsius[-half_window:]
    else:
        filtered_temp = temp_celsius
    
    # Step 2: Create uniform time grid at target resolution
    t_min = time_ms[0]
    t_max = time_ms[-1]
    n_samples = int(np.ceil((t_max - t_min) / resolution_ms)) + 1
    uniform_time = np.linspace(t_min, t_max, n_samples)
    
    # Step 3: Interpolate filtered data onto uniform grid
    resampled_temp = np.interp(uniform_time, time_ms, filtered_temp)
    
    return uniform_time, resampled_temp


def plot_resampled_curves(heating_curves, resolution_ms=2.0, output_file=None):
    """
    Plot heating curves resampled to a fixed time resolution using averaging.
    
    Args:
        heating_curves: List of heating curve dictionaries
        resolution_ms: Target time resolution in milliseconds (default: 2.0)
        output_file: Optional filename to save the plot
    """
    if len(heating_curves) == 0:
        print("No heating curves to plot!")
        return
    
    n_curves = len(heating_curves)
    
    # Create figure with subplots
    fig, axes = plt.subplots(n_curves, 1, figsize=(12, 3 * n_curves))
    
    # Handle single subplot case
    if n_curves == 1:
        axes = [axes]
    
    for idx, curve in enumerate(heating_curves):
        ax = axes[idx]
        data = curve['data']
        metadata = curve['metadata']
        
        # Resample the data
        resampled_time, resampled_temp = resample_curve_with_averaging(
            data['time_ms'], data['temp_celsius'], resolution_ms
        )
        
        # Plot both original and resampled
        ax.plot(data['time_ms'], data['temp_celsius'], 
                linewidth=0.5, color='lightgray', alpha=0.5, label='Original')
        ax.plot(resampled_time, resampled_temp, 
                linewidth=2.0, color='steelblue', marker='o', markersize=3,
                label=f'Resampled ({resolution_ms}ms avg)')
        
        ax.set_xlabel('Time since inlet entry (ms)', fontsize=10)
        ax.set_ylabel('Temperature (°C)', fontsize=10)
        ax.set_title(f'Segment #{metadata.get("segment_number", idx+1)} - Resampled to {resolution_ms}ms Resolution',
                     fontsize=11, fontweight='bold')
        ax.grid(True, alpha=0.3)
        ax.legend(loc='best', fontsize=9)
        
        # Add statistics
        max_temp = np.max(resampled_temp)
        min_temp = np.min(resampled_temp)
        avg_temp = np.mean(resampled_temp)
        n_original = len(data['time_ms'])
        n_resampled = len(resampled_time)
        
        textstr = (f"Original points: {n_original}\n"
                  f"Resampled points: {n_resampled}\n"
                  f"Max temp: {max_temp:.1f}°C\n"
                  f"Min temp: {min_temp:.1f}°C\n"
                  f"Avg temp: {avg_temp:.1f}°C")
        
        ax.text(0.02, 0.98, textstr,
                transform=ax.transAxes,
                fontsize=9,
                verticalalignment='top',
                bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.5))
    
    plt.tight_layout()
    
    # Save or show
    if output_file:
        plt.savefig(output_file, dpi=150, bbox_inches='tight')
        print(f"✓ Figure saved: {output_file}")
    else:
        plt.show()


def plot_statistics(heating_curves, output_file=None):
    """
    Plot statistical summary across all segments.
    
    Args:
        heating_curves: List of heating curve dictionaries
        output_file: Optional filename to save the plot
    """
    if len(heating_curves) == 0:
        print("No heating curves to plot!")
        return
    
    # Extract statistics for each segment
    segment_numbers = []
    max_temps = []
    avg_temps = []
    transit_times = []
    
    for curve in heating_curves:
        data = curve['data']
        metadata = curve['metadata']
        
        segment_numbers.append(metadata.get('segment_number', 0))
        max_temps.append(np.max(data['temp_celsius']))
        avg_temps.append(np.mean(data['temp_celsius']))
        transit_times.append(metadata.get('transit_time_ms', data['time_ms'][-1]))
    
    # Create subplots
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    
    # Plot 1: Max temperature per segment
    axes[0].bar(range(len(heating_curves)), max_temps, color='steelblue', alpha=0.7)
    axes[0].set_xlabel('Segment Index', fontsize=11)
    axes[0].set_ylabel('Max Temperature (°C)', fontsize=11)
    axes[0].set_title('Maximum Temperature per Segment', fontsize=12, fontweight='bold')
    axes[0].grid(True, alpha=0.3, axis='y')
    
    # Plot 2: Average temperature per segment
    axes[1].bar(range(len(heating_curves)), avg_temps, color='coral', alpha=0.7)
    axes[1].set_xlabel('Segment Index', fontsize=11)
    axes[1].set_ylabel('Average Temperature (°C)', fontsize=11)
    axes[1].set_title('Average Temperature per Segment', fontsize=12, fontweight='bold')
    axes[1].grid(True, alpha=0.3, axis='y')
    
    # Plot 3: Transit time per segment
    axes[2].bar(range(len(heating_curves)), transit_times, color='seagreen', alpha=0.7)
    axes[2].set_xlabel('Segment Index', fontsize=11)
    axes[2].set_ylabel('Transit Time (ms)', fontsize=11)
    axes[2].set_title('Transit Time per Segment', fontsize=12, fontweight='bold')
    axes[2].grid(True, alpha=0.3, axis='y')
    
    plt.tight_layout()
    
    # Save or show
    if output_file:
        plt.savefig(output_file, dpi=150, bbox_inches='tight')
        print(f"✓ Figure saved: {output_file}")
    else:
        plt.show()


def main():
    parser = argparse.ArgumentParser(
        description='Plot heating curves from CSV files',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Plot all CSV files in heating_curves/ directory
  python plot_heating_curves.py

  # Plot CSV files from custom directory
  python plot_heating_curves.py --dir custom_dir/

  # Plot specific files
  python plot_heating_curves.py --files segment_01.csv segment_02.csv

  # Create all plot types and save to files
  python plot_heating_curves.py --save-all
        """
    )
    
    parser.add_argument('--dir', type=str, default='heating_curves',
                        help='Directory containing CSV files (default: heating_curves)')
    parser.add_argument('--files', nargs='+', type=str,
                        help='Specific CSV files to plot')
    parser.add_argument('--plot-type', choices=['single', 'overlay', 'stats', 'resampled', 'all'],
                        default='all',
                        help='Type of plot to create (default: all)')
    parser.add_argument('--resolution-ms', type=float, default=2.0,
                        help='Time resolution in milliseconds for resampled plot (default: 2.0)')
    parser.add_argument('--save-all', action='store_true',
                        help='Save all plots to PNG files instead of displaying')
    parser.add_argument('--export-resampled', action='store_true',
                        help='Export resampled data to CSV files')
    parser.add_argument('--resampled-dir', type=str, default='heating_curves_resampled',
                        help='Directory for resampled CSV files (default: heating_curves_resampled)')
    parser.add_argument('--output-prefix', type=str, default='heating_curves',
                        help='Prefix for output files when using --save-all (default: heating_curves)')
    
    args = parser.parse_args()
    
    # Determine which files to load
    if args.files:
        csv_files = args.files
    else:
        # Find all CSV files in directory
        search_pattern = os.path.join(args.dir, '*.csv')
        csv_files = glob.glob(search_pattern)
        
        if not csv_files:
            print(f"No CSV files found in directory: {args.dir}")
            print(f"Search pattern: {search_pattern}")
            return
    
    # Sort files by name for consistent ordering
    csv_files = sorted(csv_files)
    
    print(f"Found {len(csv_files)} CSV file(s) to plot:")
    for f in csv_files:
        print(f"  - {f}")
    print()
    
    # Read all CSV files
    heating_curves = []
    for filepath in csv_files:
        try:
            curve = read_heating_curve_csv(filepath)
            heating_curves.append(curve)
            print(f"✓ Loaded: {filepath}")
        except Exception as e:
            print(f"✗ Error loading {filepath}: {e}")
    
    if not heating_curves:
        print("\nNo valid heating curves loaded!")
        return
    
    print(f"\n✓ Successfully loaded {len(heating_curves)} heating curve(s)\n")
    
    # Generate timestamp for output files
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    
    # Export resampled data if requested
    if args.export_resampled:
        print(f"\nExporting resampled data to CSV (resolution: {args.resolution_ms}ms)...")
        os.makedirs(args.resampled_dir, exist_ok=True)
        
        for idx, curve in enumerate(heating_curves):
            data = curve['data']
            metadata = curve['metadata']
            
            # Resample the data
            resampled_time, resampled_temp = resample_curve_with_averaging(
                data['time_ms'], data['temp_celsius'], args.resolution_ms
            )
            
            # Create CSV filename
            segment_num = metadata.get('segment_number', idx + 1)
            csv_filename = os.path.join(
                args.resampled_dir, 
                f"segment_{segment_num:02d}_resampled_{args.resolution_ms}ms_{timestamp}.csv"
            )
            
            # Write CSV file
            with open(csv_filename, 'w', newline='') as csvfile:
                writer = csv.writer(csvfile)
                # Write header with metadata
                writer.writerow(['# Resampled Segment Temperature History'])
                writer.writerow([f'# Original Segment Number: {segment_num}'])
                writer.writerow([f'# Resolution: {args.resolution_ms} ms'])
                writer.writerow([f'# Original Data Points: {len(data["time_ms"])}'])
                writer.writerow([f'# Resampled Data Points: {len(resampled_time)}'])
                writer.writerow([f'# Inlet Time (µs): {metadata.get("inlet_time_us", "N/A")}'])
                writer.writerow([f'# Outlet Time (µs): {metadata.get("outlet_time_us", "N/A")}'])
                writer.writerow([f'# Transit Time (ms): {metadata.get("transit_time_ms", resampled_time[-1] if len(resampled_time) > 0 else "N/A")}'])
                writer.writerow(['# '])
                writer.writerow(['# Note: Data was low-pass filtered with moving average before resampling'])
                writer.writerow(['# to avoid aliasing artifacts.'])
                writer.writerow(['# '])
                # Write column headers
                writer.writerow(['Time_Since_Inlet_ms', 'Temperature_Celsius'])
                # Write data rows
                for t, temp in zip(resampled_time, resampled_temp):
                    writer.writerow([f'{t:.6f}', f'{temp:.4f}'])
            
            print(f"  ✓ Saved: {csv_filename}")
        
        print(f"\n✓ All {len(heating_curves)} resampled curves exported to {args.resampled_dir}/\n")
    
    # Create plots based on requested type
    if args.plot_type in ['single', 'all']:
        print("Creating individual segment plots...")
        output_file = f"{args.output_prefix}_individual_{timestamp}.png" if args.save_all else None
        plot_single_curves(heating_curves, output_file)
    
    if args.plot_type in ['overlay', 'all']:
        print("Creating overlay plot...")
        output_file = f"{args.output_prefix}_overlay_{timestamp}.png" if args.save_all else None
        plot_overlay_curves(heating_curves, output_file)
    
    if args.plot_type in ['resampled', 'all']:
        print(f"Creating resampled plot ({args.resolution_ms}ms resolution with averaging)...")
        output_file = f"{args.output_prefix}_resampled_{timestamp}.png" if args.save_all else None
        plot_resampled_curves(heating_curves, args.resolution_ms, output_file)
    
    if args.plot_type in ['stats', 'all']:
        print("Creating statistics plot...")
        output_file = f"{args.output_prefix}_statistics_{timestamp}.png" if args.save_all else None
        plot_statistics(heating_curves, output_file)
    
    if not args.save_all:
        print("\nDisplaying plots...")
        plt.show()
    else:
        print("\n✓ All plots saved!")


if __name__ == '__main__':
    main()
